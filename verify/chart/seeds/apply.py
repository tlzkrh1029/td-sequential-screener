def main():
    if len(sys.argv) == 2 and sys.argv[1] == '--list':
        for k, v in SEEDS.items(): print(f'{k}\t{", ".join(sorted(set(r[0] for r in v[1])))}\t{v[0]}')
        return
    if len(sys.argv) == 3 and sys.argv[1] == '--check':
        bad = 0
        for k, (what, reps) in SEEDS.items():
            for path, old, new in reps:
                n = open(os.path.join(sys.argv[2], path), encoding='utf8').read().count(old)
                if n != 1: bad += 1; print(f'seed {k}: the text to replace occurs {n} times in {path}: {old[:70]!r}')
        print(f'{len(SEEDS)} seeds, {bad} that do not fit')
        sys.exit(1 if bad else 0)
    if len(sys.argv) != 3 or sys.argv[1] not in SEEDS: sys.exit('usage: apply.py <seed> <copyDir> | --list | --check <repoDir>')
    name, root = sys.argv[1], sys.argv[2]
    if os.path.isdir(os.path.join(root, '.git')): sys.exit('refusing to seed a git checkout: seed a copy')
    what, reps = SEEDS[name]
    texts = {}
    for path, old, new in reps:
        s = texts.get(path) or open(os.path.join(root, path), encoding='utf8').read()
        n = s.count(old)
        if n != 1: sys.exit(f'seed {name}: the text to replace occurs {n} times in {path}')
        texts[path] = s.replace(old, new)
    for path, s in texts.items(): open(os.path.join(root, path), 'w', encoding='utf8').write(s)
    print(f'seeded {name}: {what}')
main()
